#!/usr/bin/env python3
"""Generate/check the L1 roll-up from declared L2 parents and trace dispositions."""
import argparse
from collections import Counter, defaultdict
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent.parent
RANK = {"Traced": 0, "Partly traced": 1, "Backlog": 2}
STATUS = {
    "Tested": "Traced",
    "Out of scope (approved)": "Traced",
    "Partly tested": "Partly traced",
    "Inspection": "Partly traced",
    "Deviation (needs approval)": "Backlog",
    "Open": "Backlog",
}


def generate(l1: str, l2: str, trace: str) -> tuple[str, Counter]:
    parents = re.findall(r"^### (L1-[A-Z]+-\d{3})$", l1, re.M)
    if not parents or len(parents) != len(set(parents)):
        raise ValueError("missing or duplicate L1 IDs")
    children = defaultdict(list)
    declared = set()
    for ident, body in re.findall(
            r"^#### (L2-[A-Z]+-\d{3})\n(.*?)(?=^#### |^## |\Z)", l2, re.M | re.S):
        links = re.findall(r"^\*\*Parent\*\*: (L1-[A-Z]+-\d{3})$", body, re.M)
        if ident in declared or len(links) != 1 or links[0] not in parents:
            raise ValueError(f"{ident}: duplicate ID or invalid parent")
        declared.add(ident)
        children[links[0]].append(ident)
    dispositions = {}
    for line in trace.splitlines():
        if not line.startswith("| L2-"):
            continue
        cells = [c.strip() for c in line.strip("|").split("|")]
        if len(cells) != 4:
            raise ValueError("malformed L2 trace row")
        ident, disposition, _, notes = cells
        if ident in dispositions or disposition not in STATUS:
            raise ValueError(f"{ident}: duplicate or unresolved disposition")
        if disposition in {"Deviation (needs approval)", "Open"} and "Backlog (approved 2026-11-22)" not in notes:
            raise ValueError(f"{ident}: backlog approval is not recorded")
        dispositions[ident] = disposition
    if not declared or set(dispositions) != declared:
        raise ValueError("L2 declarations and trace IDs differ")
    lines = [
        "# L1 traceability roll-up", "",
        "Generated by `python3 scripts/trace_l1.py --write`; do not edit this table.",
        "CI runs `python3 scripts/trace_l1.py` to reject drift.", "",
        "Each L2 child comes from its Parent field in [L2-REQ.md](L2-REQ.md).",
        "The worst child decides: approved backlog Deviation or Open => **Backlog**;",
        "otherwise any Partly tested or Inspection => **Partly traced**; otherwise",
        "all children Tested or Out of scope (approved) => **Traced**.",
        "An L1 with no declared L2 children is **Backlog** (missing derivation),",
        "never a vacuous pass. Child dispositions come from [TRACE-L2.md](TRACE-L2.md).", "",
        "This is a roll-up of mapped L2 evidence and approved scope, not independent",
        "verification of literal L1 wording or release qualification. Approved L2",
        "rewordings do not silently rewrite L1; residual L1 wording reconciliation",
        "and missing derivations remain explicit follow-up work. Production NFS",
        "remains disabled and all release gates remain open.", "",
        "| L1 requirement | L2 children | Roll-up status |",
        "|---|---|---|",
    ]
    counts = Counter()
    for parent in parents:
        ids = sorted(children[parent])
        status = max((STATUS[dispositions[i]] for i in ids), key=RANK.get) if ids else "Backlog"
        counts[status] += 1
        links = ", ".join(ids) if ids else "None — missing L2 derivation"
        lines.append(f"| {parent} | {links} | {status} |")
    lines.extend(["", f"Totals: **{len(parents)} L1 requirements; " +
                  "; ".join(f"{name} {counts[name]}" for name in RANK) + ".**", ""])
    return "\n".join(lines), counts


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="regenerate docs/TRACE-L1.md")
    args = parser.parse_args()
    try:
        result, counts = generate(*((ROOT / "docs" / name).read_text(encoding="utf-8")
                                    for name in ["L1-REQ.md", "L2-REQ.md", "TRACE-L2.md"]))
        output = ROOT / "docs/TRACE-L1.md"
        if args.write:
            output.write_text(result, encoding="utf-8")
        elif not output.is_file() or output.read_text(encoding="utf-8") != result:
            print("ERROR: L1 roll-up drift; run python3 scripts/trace_l1.py --write")
            return 1
    except (OSError, ValueError) as error:
        print(f"ERROR: {error}")
        return 1
    print("L1 roll-up: " + ", ".join(f"{k} {counts[k]}" for k in RANK))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
